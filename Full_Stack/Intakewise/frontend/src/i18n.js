export function translate(language, key, values = {}) {
  const path = key.split(".");
  const findIn = source => path.reduce((node, part) => node?.[part], source);
  const find = locale => findIn(extraMessages[locale]) || findIn(messages[locale]);
  const template = find(language) || find("en") || key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function supportedLanguage(value) {
  return value === "es" ? "es" : "en";
}

